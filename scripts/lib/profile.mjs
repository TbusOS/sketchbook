// profile.mjs — the README for github.com/TbusOS (the TbusOS/TbusOS repository).
//
// Pictures are linked by absolute URL from the sketchbook web page, so when the
// daily job redraws a card with new numbers the profile shows it too — the
// profile repository itself never needs a commit, and the Action never needs
// write access to a second repository. Copy this file there by hand when its
// text changes (docs/PLAN.md, stage 4).

export function profile(model) {
  const base = model.site.replace(/\/$/, '');
  const s = model.stats;
  const pic = (name, alt, width) =>
    `<picture><source media="(prefers-color-scheme: dark)" srcset="${base}/art/${name}-dark.svg"><img src="${base}/art/${name}-light.svg" alt="${alt}" width="${width}"></picture>`;
  const out = [];
  out.push(`<!-- Generated by TbusOS/sketchbook (scripts/lib/profile.mjs). Edit there, then copy here. -->`);
  out.push(`<p align="center"><a href="https://github.com/TbusOS/sketchbook">${pic('banner-en', `TbusOS sketchbook: ${s.projects} open-source projects`, '100%')}</a></p>`);
  out.push('');
  out.push(`<p align="center">Tools for AI coding agents, Linux kernel &amp; driver work, and learning LLMs —<br><b>${s.projects} open-source projects</b>, all collected in one hand-drawn <a href="https://github.com/TbusOS/sketchbook"><b>sketchbook</b></a>.</p>`);
  out.push(`<p align="center"><sub>给 AI 编程 Agent 用的工具、Linux 内核与驱动开发、大模型学习 —— ${s.projects} 个开源项目,都收在<a href="https://github.com/TbusOS/sketchbook/blob/main/README_zh.md">速写本</a>里。</sub></p>`);
  out.push('');
  out.push('<p align="center">');
  model.featured.forEach((r, i) => {
    out.push(`<a href="${r.url}">${pic(`card-${r.name}-en`, `${r.name}: ${r.en}`, '49%')}</a>${i % 2 ? '<br>' : ''}`);
  });
  out.push('</p>');
  out.push('');
  out.push(`<p align="center"><a href="${model.site}"><b>See all ${s.projects} projects →</b></a> · <a href="${model.site}?lang=zh">查看全部 ${s.projects} 个项目 →</a></p>`);
  out.push('');
  return out.join('\n');
}
